#!/usr/bin/env python3
"""Regenerates BibleAICore/Sources/BibleAICore/Prompts/SharedTexts.swift from shared/*.txt|sql.

The Swift constants are exact copies of the shared contract files; SharedTextsTests fails when they drift.
Run: python3 ios/scripts/sync_shared_texts.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHARED = ROOT / "shared"
OUT = ROOT / "ios/BibleAICore/Sources/BibleAICore/Prompts/SharedTexts.swift"

FILES = [
    ("systemPrompt", "system_prompt.txt", "System prompt (§1). Use `PromptBuilder`, which strips the trailing newline."),
    ("memoryExtractionPrompt", "memory_extraction_prompt.txt", "Memory extraction prompt (§4). `{{user_message}}` is replaced by the user's message."),
    ("summarizationPrompt", "summarization_prompt.txt", "Rolling summary prompt (§5). Placeholders: `{{previous_summary}}`, `{{messages}}`."),
    ("stopwords", "stopwords.txt", "FTS stopwords (§3), one per line."),
    ("userSchema", "schema_user.sql", "`user.sqlite` schema."),
]


def literal(text: str) -> str:
    assert '"""#' not in text
    return '#"""\n' + text + '\n"""#'


parts = [
    "// GENERATED by ios/scripts/sync_shared_texts.py from shared/. Do not edit by hand.",
    "// SharedTextsTests asserts these constants equal the files in shared/.",
    "",
    "/// Verbatim copies of the cross-component contract files in `shared/`.",
    "public enum SharedTexts {",
]
for name, filename, doc in FILES:
    text = (SHARED / filename).read_text(encoding="utf-8")
    parts.append(f"    /// {doc}")
    parts.append(f"    /// Source: `shared/{filename}`.")
    parts.append(f"    public static let {name} = {literal(text)}")
    parts.append("")
parts[-1] = "}"
OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
print(f"wrote {OUT}")
