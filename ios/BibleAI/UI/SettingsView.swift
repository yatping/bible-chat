import BibleAICore
import SwiftUI

struct SettingsView: View {
    @Environment(AppEnvironment.self) private var env

    var body: some View {
        @Bindable var env = env
        NavigationStack {
            List {
                Section("Personalisation") {
                    NavigationLink {
                        MemorySettingsView()
                    } label: {
                        LabeledContent("Memory", value: env.memoryEnabled ? "On" : "Off")
                    }
                }

                Section("Models") {
                    ForEach(env.modelStore.manifest.models) { model in
                        LabeledContent(model.role == .generator ? "Answer model" : "Search model") {
                            Text(env.modelStore.state(of: model).isReady ? "Downloaded" : "Not downloaded")
                        }
                        .swipeActions {
                            Button("Delete", role: .destructive) { env.modelStore.delete(model) }
                        }
                    }
                    LabeledContent("Inference", value: EngineFactory.hasLlama ? "llama.cpp (Metal)" : "Unavailable")
                }

                Section("Bible content") {
                    if let content = env.content {
                        LabeledContent("Translation", value: content.translation)
                        if let built = content.meta["built_at"] { LabeledContent("Built", value: built) }
                    } else {
                        Text(env.contentMessage ?? "Not available").foregroundStyle(.secondary)
                    }
                }

                #if DEBUG
                Section("Developer") {
                    Toggle("Use mock model", isOn: $env.useMockModel)
                }
                #endif

                Section("About") {
                    Text("Scripture: World English Bible (public domain). Answers are generated by an on-device model and can be wrong — check the cited sources.")
                        .font(.footnote)
                        .foregroundStyle(.secondary)
                }
            }
            .navigationTitle("Settings")
        }
    }
}
